---@param desc string
---@return string
function M.translate(desc)
  local exact = M.dict[desc]
  if exact then
    return exact
  end

  -- 有些条目由 rhs 回退而来，可能带前导空格、冒号或分组加号
  local trimmed = desc:match("^%s*(.-)%s*$")
  local candidates = { desc, trimmed }
  if trimmed then
    candidates[#candidates + 1] = trimmed:match("^:%s*(.*)$")
    candidates[#candidates + 1] = trimmed:match("^%+(.*)$")
  end
  for _, key in ipairs(candidates) do
    if key and M.dict[key] then
      return M.dict[key]
    end
  end

  -- Snacks toggles 会根据状态把描述动态改写成 Enable/Disable xxx
  local name = desc:match("^Enable (.+)$")
  if name and M.dict[name] then
    return "启用" .. M.dict[name]
  end
  name = desc:match("^Disable (.+)$")
  if name and M.dict[name] then
    return "禁用" .. M.dict[name]
  end

  -- which-key 为未命名分组生成的 "N keymaps"
  local count = desc:match("^(%d+) keymaps?$")
  if count then
    return count .. " 个快捷键"
  end

  return desc
end

return M
